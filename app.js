function getSavedLanguage() {
  try {
    const saved = window.localStorage.getItem('3tstone-language');
    return translations[saved] ? saved : 'en';
  } catch {
    return 'en';
  }
}

function updateLegalLinks(language) {
  document.querySelectorAll('.legal-links[data-product]').forEach((group) => {
    const product = group.dataset.product;
    group.querySelectorAll('a[data-doc]').forEach((link) => {
      const productDocuments = documentURLs[language]?.[product] || documentURLs.en[product];
      if (productDocuments?.[link.dataset.doc]) link.href = productDocuments[link.dataset.doc];
    });
  });
}

function setLanguage(language) {
  const copy = translations[language];
  if (!copy) return;

  document.documentElement.lang = copy.htmlLang;
  document.title = `3TStone LLC — ${copy.brandTagline}`;
  languageLabel.textContent = copy.code;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (copy[key]) element.textContent = copy[key];
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    const key = element.dataset.i18nAria;
    if (copy[key]) element.setAttribute('aria-label', copy[key]);
  });

  updateLegalLinks(language);
  updateDirectoryCopy(language);
  languageMenu.querySelectorAll('[data-language]').forEach((button) => {
    button.setAttribute('aria-current', button.dataset.language === language ? 'true' : 'false');
  });

  try { window.localStorage.setItem('3tstone-language', language); } catch { /* Storage may be unavailable. */ }
}

function closeLanguageMenu(restoreFocus = false) {
  languageMenu.classList.remove('is-open');
  languageTrigger.setAttribute('aria-expanded', 'false');
  if (restoreFocus) languageTrigger.focus();
}

function openLanguageMenu() {
  languageMenu.classList.add('is-open');
  languageTrigger.setAttribute('aria-expanded', 'true');
  languageOptions[0].focus();
}

function closeNavigation() {
  mainNav.classList.remove('is-open');
  menuToggle.setAttribute('aria-expanded', 'false');
}

languageTrigger.addEventListener('click', (event) => {
  event.stopPropagation();
  if (languageMenu.classList.contains('is-open')) {
    closeLanguageMenu();
  } else {
    openLanguageMenu();
  }
});

languageTrigger.addEventListener('keydown', (event) => {
  if (event.key === 'ArrowDown' || event.key === 'ArrowUp') {
    event.preventDefault();
    openLanguageMenu();
    if (event.key === 'ArrowUp') languageOptions.at(-1).focus();
  }
});

languageMenu.addEventListener('click', (event) => {
  const button = event.target.closest('[data-language]');
  if (!button) return;
  setLanguage(button.dataset.language);
  closeLanguageMenu(true);
});

languageMenu.addEventListener('keydown', (event) => {
  const currentIndex = languageOptions.indexOf(document.activeElement);
  if (event.key === 'Escape') {
    event.preventDefault();
    closeLanguageMenu(true);
    return;
  }
  if (!['ArrowDown', 'ArrowUp', 'Home', 'End'].includes(event.key)) return;

  event.preventDefault();
  let nextIndex = currentIndex;
  if (event.key === 'ArrowDown') nextIndex = (currentIndex + 1) % languageOptions.length;
  if (event.key === 'ArrowUp') nextIndex = (currentIndex - 1 + languageOptions.length) % languageOptions.length;
  if (event.key === 'Home') nextIndex = 0;
  if (event.key === 'End') nextIndex = languageOptions.length - 1;
  languageOptions[nextIndex].focus();
});

menuToggle.addEventListener('click', () => {
  const isOpen = mainNav.classList.toggle('is-open');
  menuToggle.setAttribute('aria-expanded', String(isOpen));
});

mainNav.addEventListener('click', (event) => {
  if (event.target.matches('a')) closeNavigation();
});

document.addEventListener('click', (event) => {
  if (!event.target.closest('.language-picker')) closeLanguageMenu();
});

document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape') {
    if (languageMenu.classList.contains('is-open')) closeLanguageMenu(true);
    closeNavigation();
  }
});


const categoryTabs = [...document.querySelectorAll('[data-category-tab]')];
const categoryPanels = [...document.querySelectorAll('[data-category-panel]')];
const productCategoryStorageKey = '3tstone-product-category';

function updateDirectoryCopy(language) {
  const copy = directoryTranslations[language] || directoryTranslations.en;
  document.querySelectorAll('[data-directory-i18n]').forEach((element) => {
    const value = copy[element.dataset.directoryI18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll('[data-directory-i18n-aria]').forEach((element) => {
    const value = copy[element.dataset.directoryI18nAria];
    if (value) element.setAttribute('aria-label', value);
  });
}

function setProductCategory(category) {
  const tab = categoryTabs.find((item) => item.dataset.categoryTab === category);
  if (!tab) return;
  categoryTabs.forEach((item) => {
    const active = item === tab;
    item.classList.toggle('is-active', active);
    item.setAttribute('aria-selected', String(active));
    item.tabIndex = active ? 0 : -1;
  });
  categoryPanels.forEach((panel) => { panel.hidden = panel.dataset.categoryPanel !== category; });
  try { window.localStorage.setItem(productCategoryStorageKey, category); } catch { /* Storage may be unavailable. */ }
}

function getSavedProductCategory() {
  try {
    const saved = window.localStorage.getItem(productCategoryStorageKey);
    return categoryTabs.some((tab) => tab.dataset.categoryTab === saved) ? saved : 'life';
  } catch {
    return 'life';
  }
}

categoryTabs.forEach((tab, index) => {
  tab.addEventListener('click', () => setProductCategory(tab.dataset.categoryTab));
  tab.addEventListener('keydown', (event) => {
    if (!['ArrowLeft', 'ArrowRight', 'Home', 'End'].includes(event.key)) return;
    event.preventDefault();
    let nextIndex = index;
    if (event.key === 'ArrowLeft') nextIndex = (index - 1 + categoryTabs.length) % categoryTabs.length;
    if (event.key === 'ArrowRight') nextIndex = (index + 1) % categoryTabs.length;
    if (event.key === 'Home') nextIndex = 0;
    if (event.key === 'End') nextIndex = categoryTabs.length - 1;
    const next = categoryTabs[nextIndex];
    setProductCategory(next.dataset.categoryTab);
    next.focus();
  });
});

document.querySelectorAll('.product-row-legal').forEach((details) => {
  details.addEventListener('toggle', () => {
    details.closest('.product-row')?.classList.toggle('is-legal-open', details.open);
  });
});

setProductCategory(getSavedProductCategory());

document.getElementById('year').textContent = new Date().getFullYear();
setLanguage(getSavedLanguage());
